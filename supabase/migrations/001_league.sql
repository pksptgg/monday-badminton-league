create extension if not exists pgcrypto;

create table if not exists public.league_state (
  id bigint generated by default as identity primary key,
  data jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_pins (
  id boolean primary key default true check (id),
  pin_hash text not null,
  updated_at timestamptz not null default now()
);

insert into public.admin_pins (id, pin_hash)
values (true, extensions.crypt('123456', extensions.gen_salt('bf')))
on conflict (id) do nothing;

alter table public.league_state enable row level security;
alter table public.admin_pins enable row level security;
alter table public.league_state replica identity full;

create policy "Public can read league state"
on public.league_state for select
to anon, authenticated
using (true);

create or replace function public.verify_admin_pin(input_pin text)
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_pins
    where id = true and pin_hash = extensions.crypt(input_pin, pin_hash)
  );
$$;

create or replace function public.update_league_state(input_pin text, input_data jsonb)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.verify_admin_pin(input_pin) then
    return false;
  end if;
  update public.league_state set data = input_data, updated_at = now() where id = 1;
  return found;
end;
$$;

create or replace function public.change_admin_pin(current_pin text, new_pin text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if new_pin !~ '^\d{6}$' or not public.verify_admin_pin(current_pin) then
    return false;
  end if;
  update public.admin_pins set pin_hash = extensions.crypt(new_pin, extensions.gen_salt('bf')), updated_at = now() where id = true;
  return found;
end;
$$;

revoke all on function public.verify_admin_pin(text) from public;
revoke all on function public.update_league_state(text, jsonb) from public;
revoke all on function public.change_admin_pin(text, text) from public;
grant execute on function public.verify_admin_pin(text) to anon, authenticated;
grant execute on function public.update_league_state(text, jsonb) to anon, authenticated;
grant execute on function public.change_admin_pin(text, text) to anon, authenticated;

do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'league_state') then
    alter publication supabase_realtime add table public.league_state;
  end if;
end $$;
